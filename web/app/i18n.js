      var LANG = 'en';
      try {
        var savedLang = window.localStorage.getItem('btm.lang');
        if (savedLang && STRINGS[savedLang]) LANG = savedLang;
      } catch (e) {}
      // Thiếu key → trả lại chính key (không crash). {x} thay bằng vars.x.
      function tx(key, vars) {
        var table = STRINGS[LANG] || STRINGS.en;
        var str = Object.prototype.hasOwnProperty.call(table, key) ? table[key]
          : (Object.prototype.hasOwnProperty.call(STRINGS.en, key) ? STRINGS.en[key] : key);
        if (vars) {
          str = str.replace(/\{(\w+)\}/g, function (m, k) { return Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : m; });
        }
        return str;
      }
      function applyI18n(root) {
        var scope = root || document;
        scope.querySelectorAll('[data-i18n]').forEach(function (el) { el.textContent = tx(el.getAttribute('data-i18n')); });
        scope.querySelectorAll('[data-i18n-aria]').forEach(function (el) { el.setAttribute('aria-label', tx(el.getAttribute('data-i18n-aria'))); });
        scope.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) { el.setAttribute('placeholder', tx(el.getAttribute('data-i18n-placeholder'))); });
        scope.querySelectorAll('[data-i18n-title]').forEach(function (el) { el.setAttribute('title', tx(el.getAttribute('data-i18n-title'))); });
        scope.querySelectorAll('[data-i18n-alt]').forEach(function (el) { el.setAttribute('alt', tx(el.getAttribute('data-i18n-alt'))); });
      }
      applyI18n();
